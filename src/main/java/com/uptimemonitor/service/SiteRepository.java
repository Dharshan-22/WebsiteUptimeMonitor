package com.uptimemonitor.service;

import com.uptimemonitor.model.CheckResult;
import com.uptimemonitor.model.MonitoredSite;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Repository;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.LocalDateTime;
import java.util.List;

/**
 * MySQL-backed repository for monitored sites.
 *
 * Replaces the Phase 2 in-memory {@code MonitoringStore}.
 * Uses Spring's {@link JdbcTemplate} — a thin, beginner-friendly wrapper
 * around plain JDBC that handles connection management and exception
 * translation automatically.
 *
 * <p>The {@code check_history} table is written by
 * {@link CheckHistoryRepository}; this class only manages
 * {@code monitored_sites}.</p>
 *
 * <h3>Thread safety</h3>
 * JdbcTemplate is thread-safe by design (Spring docs). No additional
 * synchronisation is required here.
 */
@Repository
public class SiteRepository {

    private final JdbcTemplate jdbc;

    public SiteRepository(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    // ── RowMapper ─────────────────────────────────────────────────────────────

    /**
     * Converts a single SQL row from {@code monitored_sites} into a
     * {@link MonitoredSite} object.
     *
     * Note: {@code lastResult} and {@code lastCheckedAt} are NOT stored in
     * {@code monitored_sites} — they come from the most recent row in
     * {@code check_history} and are loaded separately by
     * {@link CheckHistoryRepository#loadLastResultInto}.
     */
    private static final RowMapper<MonitoredSite> SITE_MAPPER = (rs, rowNum) ->
        new MonitoredSite(
            rs.getString("id"),
            rs.getString("name"),
            rs.getString("url"),
            rs.getObject("added_at", LocalDateTime.class)
        );

    // ── Write operations ──────────────────────────────────────────────────────

    /**
     * Inserts a new site into {@code monitored_sites}.
     * The site's UUID and {@code addedAt} timestamp are generated by Java
     * (in the {@link MonitoredSite} constructor) before this call.
     */
    public void save(MonitoredSite site) {
        jdbc.update(
            "INSERT INTO monitored_sites (id, name, url, added_at) VALUES (?, ?, ?, ?)",
            site.getId(),
            site.getName(),
            site.getUrl(),
            site.getAddedAt()
        );
    }

    /**
     * Deletes a site by id.
     * The {@code ON DELETE CASCADE} on {@code check_history} means MySQL will
     * also delete all history rows for this site automatically.
     */
    public void deleteById(String id) {
        jdbc.update("DELETE FROM monitored_sites WHERE id = ?", id);
    }

    // ── Read operations ───────────────────────────────────────────────────────

    /**
     * Returns the site with the given id, or {@code null} if not found.
     */
    public MonitoredSite findById(String id) {
        List<MonitoredSite> results = jdbc.query(
            "SELECT * FROM monitored_sites WHERE id = ?",
            SITE_MAPPER,
            id
        );
        return results.isEmpty() ? null : results.get(0);
    }

    /**
     * Returns all sites, ordered by the time they were added (oldest first).
     */
    public List<MonitoredSite> findAll() {
        return jdbc.query(
            "SELECT * FROM monitored_sites ORDER BY added_at ASC",
            SITE_MAPPER
        );
    }
}
