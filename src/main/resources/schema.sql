-- =============================================================================
-- Website Uptime Monitor — Phase 3 Schema
-- Database: uptime_monitor
--
-- Run this in MySQL Workbench ONCE before starting the application,
-- OR let Spring Boot run it automatically (spring.sql.init.mode=always).
--
-- Using IF NOT EXISTS means this script is safe to run multiple times
-- without destroying existing data.
-- =============================================================================

-- ── monitored_sites ──────────────────────────────────────────────────────────
-- One row per website the user has added to the dashboard.
CREATE TABLE IF NOT EXISTS monitored_sites (
    id           VARCHAR(36)  NOT NULL,          -- UUID generated by Java
    name         VARCHAR(100) NOT NULL,           -- user-supplied display name
    url          VARCHAR(2048) NOT NULL,          -- normalised http/https URL
    added_at     DATETIME     NOT NULL,           -- when the site was added
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ── check_history ────────────────────────────────────────────────────────────
-- One row per Check Now click. Grows over time; useful for Phase 4 charts.
CREATE TABLE IF NOT EXISTS check_history (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    site_id         VARCHAR(36)  NOT NULL,         -- FK → monitored_sites.id
    checked_at      DATETIME     NOT NULL,         -- timestamp of this check
    status          VARCHAR(10)  NOT NULL,         -- 'UP' or 'DOWN'
    http_status_code INT         NOT NULL,         -- e.g. 200, 404, 0
    http_status_text VARCHAR(50) NOT NULL,         -- e.g. 'OK', 'N/A'
    response_time_ms BIGINT      NOT NULL,         -- round-trip ms (0 if error)
    error_message   TEXT,                          -- NULL when check succeeded
    PRIMARY KEY (id),
    CONSTRAINT fk_history_site
        FOREIGN KEY (site_id) REFERENCES monitored_sites(id)
        ON DELETE CASCADE                          -- history removed with site
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
